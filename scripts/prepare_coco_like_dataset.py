#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import struct
import random
import shutil
from pathlib import Path


IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp", ".bmp", ".tif", ".tiff"}


def read_image_size(path: Path) -> tuple[int, int]:
    suffix = path.suffix.lower()
    with path.open("rb") as file:
        header = file.read(32)
        if suffix == ".png":
            if header[:8] != b"\x89PNG\r\n\x1a\n":
                raise ValueError(f"Unsupported PNG file: {path}")
            width, height = struct.unpack(">II", header[16:24])
            return int(width), int(height)

        if suffix in {".jpg", ".jpeg"}:
            file.seek(0)
            if file.read(2) != b"\xff\xd8":
                raise ValueError(f"Unsupported JPEG file: {path}")
            while True:
                marker_prefix = file.read(1)
                if marker_prefix != b"\xff":
                    raise ValueError(f"Invalid JPEG marker in {path}")
                marker = file.read(1)
                while marker == b"\xff":
                    marker = file.read(1)
                if marker in {b"\xc0", b"\xc1", b"\xc2", b"\xc3", b"\xc5", b"\xc6", b"\xc7", b"\xc9", b"\xca", b"\xcb", b"\xcd", b"\xce", b"\xcf"}:
                    segment_length = struct.unpack(">H", file.read(2))[0]
                    _precision = file.read(1)
                    height, width = struct.unpack(">HH", file.read(4))
                    return int(width), int(height)
                segment_length = struct.unpack(">H", file.read(2))[0]
                file.seek(segment_length - 2, 1)

    raise ValueError(f"Unsupported image format for size extraction: {path}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Restructure a flat image folder into train/valid/test directories similar to a COCO-style dataset root."
    )
    parser.add_argument("--source", required=True, help="Flat folder containing source images.")
    parser.add_argument("--output", required=True, help="Destination dataset root to create.")
    parser.add_argument("--train-ratio", type=float, default=0.8, help="Train split ratio. Default: 0.8")
    parser.add_argument("--valid-ratio", type=float, default=0.1, help="Valid split ratio. Default: 0.1")
    parser.add_argument("--seed", type=int, default=42, help="Deterministic shuffle seed. Default: 42")
    parser.add_argument(
        "--mode",
        choices=("copy", "symlink"),
        default="copy",
        help="Whether to copy files or create symlinks. Default: copy",
    )
    return parser.parse_args()


def collect_images(source: Path) -> list[Path]:
    return sorted(path for path in source.iterdir() if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES)


def write_readmes(output: Path, source: Path, counts: dict[str, int], seed: int, train_ratio: float, valid_ratio: float) -> None:
    dataset_readme = output / "README.dataset.txt"
    dataset_readme.write_text(
        "\n".join(
            [
                f"Prepared from: {source}",
                f"Seed: {seed}",
                f"Train ratio: {train_ratio}",
                f"Valid ratio: {valid_ratio}",
                f"Test ratio: {1.0 - train_ratio - valid_ratio}",
                "",
                f"Train images: {counts['train']}",
                f"Valid images: {counts['valid']}",
                f"Test images: {counts['test']}",
                "",
                "This folder matches the train/valid/test layout of Manga Bubble.v4i.coco.",
                "Annotations are not generated by this script. Add _annotations.coco.json inside each split when labels are ready.",
            ]
        )
        + "\n",
        encoding="utf-8",
    )

    roboflow_readme = output / "README.roboflow.txt"
    roboflow_readme.write_text(
        "Placeholder README to mirror the Manga Bubble.v4i.coco folder structure.\n",
        encoding="utf-8",
    )


def write_placeholder_annotations(split_dir: Path, images: list[Path]) -> None:
    image_items = []
    for index, image_path in enumerate(images, start=1):
        width, height = read_image_size(image_path)
        image_items.append(
            {
                "id": index,
                "file_name": image_path.name,
                "width": width,
                "height": height,
            }
        )
    placeholder = split_dir / "_annotations.coco.json"
    payload = {
        "info": {
            "description": "Prepared local dataset scaffold",
        },
        "licenses": [],
        "categories": [
            {"id": 1, "name": "speech_bubble", "supercategory": "text"},
            {"id": 2, "name": "narration_box", "supercategory": "text"},
            {"id": 3, "name": "sfx", "supercategory": "text"},
        ],
        "images": image_items,
        "annotations": [],
    }
    placeholder.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def materialize_file(source: Path, destination: Path, mode: str) -> None:
    if mode == "symlink":
        destination.symlink_to(source)
        return
    shutil.copy2(source, destination)


def main() -> None:
    args = parse_args()
    source = Path(args.source).expanduser().resolve()
    output = Path(args.output).expanduser().resolve()

    if not source.is_dir():
      raise SystemExit(f"Source folder does not exist: {source}")

    if args.train_ratio <= 0 or args.valid_ratio < 0 or args.train_ratio + args.valid_ratio >= 1:
      raise SystemExit("Ratios must satisfy: train_ratio > 0, valid_ratio >= 0, and train_ratio + valid_ratio < 1")

    images = collect_images(source)
    if not images:
      raise SystemExit(f"No images found in {source}")

    rng = random.Random(args.seed)
    shuffled = images[:]
    rng.shuffle(shuffled)

    total = len(shuffled)
    train_end = int(total * args.train_ratio)
    valid_end = train_end + int(total * args.valid_ratio)
    splits = {
        "train": shuffled[:train_end],
        "valid": shuffled[train_end:valid_end],
        "test": shuffled[valid_end:],
    }

    output.mkdir(parents=True, exist_ok=True)
    counts = {}
    for split, items in splits.items():
        split_dir = output / split
        split_dir.mkdir(parents=True, exist_ok=True)
        counts[split] = len(items)
        for image_path in items:
            destination = split_dir / image_path.name
            if destination.exists() or destination.is_symlink():
                destination.unlink()
            materialize_file(image_path, destination, args.mode)
        write_placeholder_annotations(split_dir, items)

    write_readmes(output, source, counts, args.seed, args.train_ratio, args.valid_ratio)

    print(f"Prepared dataset at: {output}")
    print(f"Train: {counts['train']}  Valid: {counts['valid']}  Test: {counts['test']}")


if __name__ == "__main__":
    main()
